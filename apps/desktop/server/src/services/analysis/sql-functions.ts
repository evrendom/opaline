const ALLOWED = new Set<string>([
	...AGGREGATES,
	...WINDOW,
	...OPERATORS,
	...CONDITIONAL,
	...MATH,
	...DATES,
	...STRINGS,
	...ARRAYS,
	...CONVERSION,
	...JSON_FUNCTIONS,
]);
const AGGREGATE_NAMES = new Set<string>(AGGREGATES);

/** Whether an agent's SQL may call the function, combinator forms included. */
export function isAllowedFunction(name: string): boolean {
	const lower = name.toLowerCase();
	if (ALLOWED.has(lower)) return true;
	return isAggregateWithCombinators(lower);
}

function isAggregateWithCombinators(name: string): boolean {
	let base = name;
	for (let stripped = true; stripped; ) {
		stripped = false;
		for (const suffix of COMBINATORS)
			if (base.length > suffix.length && base.endsWith(suffix)) {
				base = base.slice(0, -suffix.length);
				stripped = true;
				if (AGGREGATE_NAMES.has(base)) return true;
				break;
			}
	}
	return false;
}

